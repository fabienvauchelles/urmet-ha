BOOT_TIME = datetime(2026, 1, 1, 12, 0, 0, tzinfo=UTC)
GATE_TIMEOUT_S = 10.0
REGISTER_TIMEOUT_S = 2.0
STREAM_TIMEOUT_S = 2.0
OPEN_TIMEOUT_S = 0.5


def frozen_clock() -> datetime:
    """The clock the scenarios stamp their events with. It does not move."""
    return BOOT_TIME


class GatedCloud(FakeCloud):
    """A ``FakeCloud`` whose login blocks until released, freezing boot at REGISTER.

    Registration crosses the cloud on the worker thread before it ever reaches the
    registrar, so holding ``login`` there is what lets a scenario watch the health
    port answer while the binding does not exist yet.
    """

    def __init__(self, *, gate: threading.Event, **fields: Any) -> None:
        super().__init__(**fields)
        self._gate = gate

    def login(self, email: str, password: SecretStr) -> UserProfile:
        self._gate.wait()
        return super().login(email, password)


class GatedTransport(FakeSipTransport):
    """A ``FakeSipTransport`` whose INVITE can be held after the panel streamed.

    Holding one open freezes a command that has everything it waited for and has
    not returned yet, which is the exact window a dialog can end in.
    """

    def __init__(self, **fields: Any) -> None:
        super().__init__(**fields)
        self.invited: CallHandle | None = None
        self.inviting = threading.Event()
        self._open = threading.Event()
        self._open.set()

    def hold_invite(self) -> None:
        self._open.clear()

    def release_invite(self) -> None:
        self._open.set()

    def end_call(self, call: CallHandle) -> None:
        """Report the far end ending ``call``, the way a BYE reaches the client."""
        self._emit_state(call, CallState.ENDED)
        self.drain()

    def invite(self, door: Doorphone, *, want_video: bool) -> CallHandle:
        call = super().invite(door, want_video=want_video)
        self.invited = call
        self.inviting.set()
        if not self._open.wait(GATE_TIMEOUT_S):
            raise AssertionError("the held INVITE was never released")
        return call


class Harness:
    """The doubles, and a client built on them. Each layer builds its own on top."""

    def __init__(
        self,
        *,
        settings: Settings,
        cloud: FakeCloud,
        transport: GatedTransport,
        tap: FakeMediaTap,
        doorphone: Doorphone,
    ) -> None:
        self.settings = settings
        self.cloud = cloud
        self.transport = transport
        self.tap = tap
        self.doorphone = doorphone
        self.clock = frozen_clock
        self._client: UrmetClient | None = None

    @property
    def client(self) -> UrmetClient:
        """The client under test, built on first use."""
        if self._client is None:
            self._client = self.build_client()
        return self._client

    def build_client(self) -> UrmetClient:
        """A client over the same doubles. The transport reports to the last built."""
        return UrmetClient(self.settings, cloud=self.cloud, transport=self.transport)


def build_harness(
    *,
    registration: RegistrationBehavior = "accept",
    open_acknowledged: bool = True,
    video_ready: bool = True,
    login_gate: threading.Event | None = None,
) -> Harness:
    """Wire one cold graph over the doubles, with the failure a scenario needs armed."""
    settings = Settings(
        _env_file=None,
        email=EMAIL,
        password=CLOUD_PASSWORD,
        cloud_base_url="https://cloud.example.invalid/",
        sip_realm=REALM,
        doorphone_mac=DOORPHONE_MAC,
        doorphone_name=DOORPHONE_NAME,
        register_timeout_s=REGISTER_TIMEOUT_S,
        stream_timeout_s=STREAM_TIMEOUT_S,
        open_timeout_s=OPEN_TIMEOUT_S,
        unregister_timeout_s=REGISTER_TIMEOUT_S,
    )
    sipdata = encrypt_sipdata(SIPDATA_DOCUMENT, SIPDATA_PAD)
    cloud: FakeCloud = (
        GatedCloud(gate=login_gate, profile=PROFILE, sipdata=sipdata, behavior="ok")
        if login_gate is not None
        else FakeCloud(profile=PROFILE, sipdata=sipdata, behavior="ok")
    )
    transport = GatedTransport(
        registration=registration,
        open_acknowledged=open_acknowledged,
        video_ready=video_ready,
        realm=REALM,
    )
    return Harness(
        settings=settings,
        cloud=cloud,
        transport=transport,
        tap=FakeMediaTap(video_ready=video_ready),
        doorphone=Doorphone(mac=DOORPHONE_MAC, name=DOORPHONE_NAME),
    )


HarnessFactory = Callable[..., Harness]
