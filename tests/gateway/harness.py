"""The doubles and the cold harness the gateway scenarios are built over.

What is real is everything the gateway and the SDK own; what is faked is the two
boundaries the SDK injects, the cloud plane and the SIP transport, plus a media
tap. ``Harness`` hands a scenario the doubles and a client built on them, and the
transport is gated so a scenario can hold an INVITE open after the panel streamed,
which is the one window a dialog can end in mid-command. The clock does not move,
so ``at`` is a value a scenario can pin.
"""

